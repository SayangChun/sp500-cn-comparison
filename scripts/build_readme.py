def replace_section(text, heading, new, next_headings, insert_before=None):
    """把 heading 开头到下一个同级标题之间的内容替换成 new；不存在则插入。"""
    if heading not in text:
        if not insert_before:
            return text
        k = text.index(insert_before)
        return text[:k] + new + "\n" + text[k:]
    i = text.index(heading)
    j = len(text)
    for nh in next_headings:
        k = text.find("\n" + nh, i + len(heading))
        if k != -1:
            j = min(j, k + 1)
    return text[:i] + new + "\n" + text[j:]


